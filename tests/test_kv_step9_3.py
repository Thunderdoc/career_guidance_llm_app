# --------------------------------------------------------------------------- #
# Clip generation (ffmpeg lavfi sources — synthetic by design)
# --------------------------------------------------------------------------- #


def _ffmpeg_available() -> bool:
    return shutil.which("ffmpeg") is not None and shutil.which("ffprobe") is not None


def _make_clip(path: str, source: str, duration: int) -> str:
    subprocess.run(
        [
            "ffmpeg",
            "-y",
            "-v",
            "error",
            "-f",
            "lavfi",
            "-i",
            source,
            "-t",
            str(duration),
            "-c:v",
            "libx264",
            "-pix_fmt",
            "yuv420p",
            path,
        ],
        check=True,
        timeout=120,
    )
    return path


@pytest.fixture(scope="module")
def clips(tmp_path_factory):
    """One moving clip, one black clip, one static clip, one short
    clip — generated once for the module."""
    if not _ffmpeg_available():
        pytest.skip("ffmpeg/ffprobe not installed")
    base = tmp_path_factory.mktemp("kv93-clips")
    moving = _make_clip(str(base / "moving.mp4"), "testsrc=duration=30:size=320x240:rate=10", 30)
    black = _make_clip(
        str(base / "black.mp4"), "color=c=black:duration=30:size=320x240:rate=10", 30
    )
    static = _make_clip(
        str(base / "static.mp4"), "color=c=red:duration=30:size=320x240:rate=10", 30
    )
    short = _make_clip(str(base / "short.mp4"), "testsrc=duration=5:size=320x240:rate=10", 5)
    return {"moving": moving, "black": black, "static": static, "short": short}


