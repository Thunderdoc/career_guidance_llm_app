# Module level
# --------------------------------------------------------------------------- #


def test_moving_clip_usable(clips):
    result = check_clip(clips["moving"])
    assert result["verdict"] == "usable"
    assert result["label"] == INDICATIVE_LABEL
    assert result["confidence"] == "low"
    assert result["duration_seconds"] == pytest.approx(30.0, abs=0.5)
    assert result["frames_sampled"] == 6
    assert result["reasons"] == []
    assert all(check["passed"] for check in result["checks"])
    motion = next(c for c in result["checks"] if c["name"] == "motion")
    assert motion["value"] > 2.0  # testsrc genuinely moves


def test_black_clip_unusable(clips):
    result = check_clip(clips["black"])
    assert result["verdict"] == "unusable"
    assert result["label"] == INDICATIVE_LABEL
    assert any("too dark" in reason for reason in result["reasons"])
    assert any("no movement" in reason for reason in result["reasons"])


def test_static_colour_clip_unusable_but_not_dark(clips):
    result = check_clip(clips["static"])
    assert result["verdict"] == "unusable"
    # Red in greyscale is bright (~76) — the failure is blank + static.
    assert not any("too dark" in reason for reason in result["reasons"])
    assert any("blank or frozen" in reason for reason in result["reasons"])
    assert any("no movement" in reason for reason in result["reasons"])


def test_too_short_clip_rejected(clips):
    with pytest.raises(VideoCheckError, match="must be 30"):
        check_clip(clips["short"])


def test_too_long_clip_rejected(tmp_path):
    if not _ffmpeg_available():
        pytest.skip("ffmpeg/ffprobe not installed")
    long_clip = _make_clip(
        str(tmp_path / "long.mp4"), "testsrc=duration=70:size=320x240:rate=10", 70
    )
    with pytest.raises(VideoCheckError, match="must be 30"):
        check_clip(long_clip)


def test_non_video_file_rejected(tmp_path):
    text = tmp_path / "notes.txt"
    text.write_text("this is not a video")
    with pytest.raises(VideoCheckError, match="not a readable video"):
        check_clip(text)


def test_result_always_carries_limits(clips):
    result = check_clip(clips["moving"])
    assert "does NOT assess skill" in result["limits"]
    assert "coordinator-led practical check" in result["limits"]


