def test_video_check_rate_limited(client, clips):
    """5 checks/hour per user: the 6th is a 429. Short clips fail
    fast (duration gate), so this does not run 6 full analyses."""
    login(client, "worker-video5@example.com")
    for _ in range(5):
        with open(clips["short"], "rb") as handle:
            r = client.post(
                "/api/v1/kv/video/check",
                files={"file": ("clip.mp4", handle, "video/mp4")},
            )
        assert r.status_code == 422
    with open(clips["short"], "rb") as handle:
        r = client.post(
            "/api/v1/kv/video/check",
            files={"file": ("clip.mp4", handle, "video/mp4")},
        )
    assert r.status_code == 429


def test_video_check_leaves_no_temp_file(client, clips):
    """The uploaded clip is deleted after analysis — no .clip temp
    file survives the request."""
    login(client, "worker-video6@example.com")
    before = set(glob.glob("/tmp/tmp*.clip"))
    with open(clips["moving"], "rb") as handle:
        r = client.post(
            "/api/v1/kv/video/check",
            files={"file": ("clip.mp4", handle, "video/mp4")},
        )
    assert r.status_code == 200
    assert set(glob.glob("/tmp/tmp*.clip")) == before


def test_video_routes_404_when_flag_off(tmp_path, monkeypatch):
    """KV_VIDEO_CHECK=false means the console never mounts (Stage 1
    flag rule)."""
    import importlib

    monkeypatch.setenv("DATABASE_PATH", str(tmp_path / "app.db"))
    monkeypatch.setenv("SESSION_SECRET", "test-secret")
    monkeypatch.setenv("PUBLIC_URL", "http://testserver")
    monkeypatch.setenv("ADMIN_EMAILS", "boss@example.com")
    monkeypatch.setenv("KV_VIDEO_CHECK", "false")
    monkeypatch.delenv("PUBLIC_APP", raising=False)
    import backend.main as main

    importlib.reload(main)
    try:
        with TestClient(main.app) as test_client:
            assert test_client.get("/api/v1/kv/video/status").status_code == 404
    finally:
        importlib.reload(main)
