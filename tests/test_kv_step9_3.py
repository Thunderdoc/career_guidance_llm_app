"""Step 9.3 — video skill check (EXPERIMENTAL).

Tested honestly on SYNTHETIC clips generated by ffmpeg itself
(testsrc / solid colours) — there are no real task recordings in
the repo, and none is faked. A synthetic moving clip proves the
pipeline measures motion; a black/static clip proves the failure
paths. Nothing here measures skill.
"""

