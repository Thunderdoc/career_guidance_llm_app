def test_table_and_column_names_sqlite(tmp_path):
    """Same helpers, real SQLite: sqlite_master + PRAGMA table_info."""
    import sqlite3

    path = tmp_path / "names.db"
    with sqlite3.connect(path) as conn:
        conn.execute("CREATE TABLE widgets (id INTEGER PRIMARY KEY, label TEXT)")
        conn.execute("CREATE TABLE gadgets (id INTEGER PRIMARY KEY)")
    conn = db_layer.connect(str(path))
    assert db_layer.table_names(conn, "sqlite") == {"widgets", "gadgets"}
    assert db_layer.column_names(conn, "widgets", "sqlite") == {"id", "label"}
    assert db_layer.column_names(conn, "no_such_table", "sqlite") == set()


