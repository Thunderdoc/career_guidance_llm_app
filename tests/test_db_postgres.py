def test_postgres_executemany_translates_each_params_set(fake_pg):
    """settings.reset + content.bump_uses call conn.executemany; the
    facade loops execute() (placeholder translation per call)."""
    raw, _ = fake_pg
    conn = db_layer.connect(PG_URL)
    conn.executemany("DELETE FROM app_settings WHERE key = ?", [("a",), ("b",)])
    deletes = [s for s, _ in raw.statements if "DELETE FROM app_settings" in s]
    assert deletes == ["DELETE FROM app_settings WHERE key = %s"] * 2
    assert raw.statements[-1][1] == ("b",)


def test_postgres_executemany_empty_sequence_is_a_noop(fake_pg):
    raw, _ = fake_pg
    conn = db_layer.connect(PG_URL)
    conn.executemany("DELETE FROM t WHERE key = ?", [])
    assert raw.statements == []


def test_postgres_exit_rolls_back_failed_transaction(fake_pg):
    """A statement error caught inside the block leaves Postgres in
    INERROR; committing then would raise InFailedSqlTransaction, so
    __exit__ rolls back instead (SQLite has no such state)."""
    raw, _ = fake_pg
    conn = db_layer.connect(PG_URL)
    raw.info.transaction_status.name = "INERROR"
    with conn:
        pass  # no exception propagates — the error was caught inside
    assert raw.rollbacks == 1
    assert raw.committed == 0


def test_postgres_exit_still_commits_healthy_transaction(fake_pg):
    raw, _ = fake_pg
    conn = db_layer.connect(PG_URL)
    with conn:
        conn.execute("SELECT 1")
    assert raw.committed == 1
    assert raw.rollbacks == 0


