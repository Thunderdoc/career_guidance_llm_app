"""Phase 6: Postgres option through the central dialect layer.

No Postgres server exists in the sandbox, so the wire-level tests use a
fake ``psycopg`` module injected into ``sys.modules``: they verify the
SQL the layer *would* send (placeholder translation, DDL translation,
RETURNING id, version-table bookkeeping) without claiming a live server
round-trip. The live smoke procedure is documented in docs/DEPLOY.md.
"""

from __future__ import annotations

import sys
import types

import pytest

from career_guidance import db as db_layer
from career_guidance.config import load_settings
from career_guidance.storage import Database

PG_URL = "postgres://cguser:s3cret@db.internal:5433/careers"


# --------------------------------------------------------------------------- #
# Config selection / DSN parsing
# --------------------------------------------------------------------------- #


def test_default_is_sqlite_path():
    cfg = db_layer.resolve_database_config(environ={})
    assert cfg.dialect == "sqlite"
    assert cfg.sqlite_path == "data/career_guidance.db"
    assert cfg.placeholder == "?"


def test_database_url_wins_over_path():
    cfg = db_layer.resolve_database_config(
        environ={"DATABASE_URL": PG_URL, "DATABASE_PATH": "ignored.db"}
    )
    assert cfg.dialect == "postgres"
    assert cfg.placeholder == "%s"
    assert (cfg.host, cfg.port, cfg.dbname, cfg.user) == (
        "db.internal",
        5433,
        "careers",
        "cguser",
    )


def test_postgres_password_never_in_repr_or_label():
    cfg = db_layer.parse_database_url(PG_URL)
    assert "s3cret" not in repr(cfg)
    assert "s3cret" not in cfg.safe_label()
    assert cfg.safe_label() == "postgres://cguser@db.internal:5433/careers"


def test_postgresql_scheme_and_default_port():
    cfg = db_layer.parse_database_url("postgresql://u:p@host/mydb")
    assert cfg.dialect == "postgres"
    assert cfg.port == 5432


def test_sqlite_url_forms():
    assert db_layer.parse_database_url("sqlite:////tmp/a.db").sqlite_path == "/tmp/a.db"
    assert db_layer.parse_database_url("sqlite:///rel.db").sqlite_path == "rel.db"
    assert db_layer.parse_database_url("sqlite:///:memory:").sqlite_path == ":memory:"


def test_plain_path_is_sqlite():
    cfg = db_layer.parse_database_url("data/whatever.db")
    assert cfg.dialect == "sqlite"
    assert cfg.sqlite_path == "data/whatever.db"


def test_unknown_scheme_fails_loudly():
    with pytest.raises(ValueError, match="Unsupported DATABASE_URL"):
        db_layer.parse_database_url("mysql://u:p@host/db")


def test_settings_database_target_prefers_url(monkeypatch):
    monkeypatch.setenv("DATABASE_URL", PG_URL)
    monkeypatch.setenv("DATABASE_PATH", "file.db")
    settings = load_settings()
    assert settings.database_url == PG_URL
    assert settings.database_target == PG_URL


