def test_sqlite_database_roundtrip_unchanged(tmp_path):
    database = Database(str(tmp_path / "runs.db"))
    assert database.dialect == "sqlite"
    assert database.ping() is True
    run_id = database.save_run({"skills": "python"}, [], "offline", True)
    assert run_id == 1
    assert database.count_runs() == 1
    assert database.list_runs()[0].profile == {"skills": "python"}
