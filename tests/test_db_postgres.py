def test_translate_placeholders_postgres_escapes_percent():
    sql = "SELECT * FROM t WHERE a = ? AND b LIKE ? AND c = '100%'"
    out = db_layer.translate_placeholders(sql, "postgres")
    assert out == "SELECT * FROM t WHERE a = %s AND b LIKE %s AND c = '100%%'"
    assert db_layer.translate_placeholders(sql, "sqlite") == sql


def test_translate_ddl_identity_and_pragma():
    ddl = "CREATE TABLE t (id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT)"
    assert db_layer.translate_ddl(ddl) == (
        "CREATE TABLE t (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT)"
    )
    assert db_layer.translate_ddl("PRAGMA table_info(t)") is None
    plain = "CREATE TABLE IF NOT EXISTS x (a TEXT PRIMARY KEY)"
    assert db_layer.translate_ddl(plain) == plain


def test_alter_add_column_parse():
    stmt = "ALTER TABLE users ADD COLUMN handle TEXT NOT NULL DEFAULT ''"
    assert db_layer.alter_add_column(stmt) == ("users", "handle")
    assert db_layer.alter_add_column("CREATE TABLE x (a INT)") is None


# --------------------------------------------------------------------------- #
# Fake psycopg: connection facade + storage + migrations over "Postgres"
# --------------------------------------------------------------------------- #


class _FakeCursor:
    def __init__(self, conn) -> None:
        self._conn = conn
        self._rows: list[dict] = []
        self.rowcount = 0

    def execute(self, sql, params=None):
        self._conn.statements.append((sql, params))
        self._rows = self._conn.answer(sql, params)
        return self

    def fetchone(self):
        return self._rows[0] if self._rows else None

    def fetchall(self):
        return list(self._rows)


class _FakeRawConnection:
    """Answers just the queries the dialect-layer tests issue."""

    def __init__(self) -> None:
        self.statements: list[tuple] = []
        self.versions: list[int] = []
        self.columns: set[str] = {"id", "created_at"}
        self.committed = 0

    def cursor(self):
        return _FakeCursor(self)

    def answer(self, sql, params):
        if "information_schema.columns" in sql:
            return [{"column_name": c} for c in sorted(self.columns)]
        if "FROM schema_migrations" in sql:
            return [{"version": v} for v in self.versions]
        if "INSERT INTO schema_migrations" in sql:
            self.versions.append(params[0])
            return []
        if "RETURNING id" in sql:
            return [{"id": 42}]
        if sql.startswith("SELECT version"):
            return [{"version": v} for v in self.versions]
        return []

    def commit(self):
        self.committed += 1

    def rollback(self):
        pass

    def close(self):
        pass


@pytest.fixture()
def fake_pg(monkeypatch):
    raw = _FakeRawConnection()
    captured = {}

    def _connect(dsn, row_factory=None):
        captured["dsn"] = dsn
        captured["row_factory"] = row_factory
        return raw

    fake = types.ModuleType("psycopg")
    fake.connect = _connect  # type: ignore[attr-defined]
    rows_mod = types.ModuleType("psycopg.rows")
    rows_mod.dict_row = object()  # type: ignore[attr-defined]
    fake.rows = rows_mod  # type: ignore[attr-defined]
    monkeypatch.setitem(sys.modules, "psycopg", fake)
    monkeypatch.setitem(sys.modules, "psycopg.rows", rows_mod)
    return raw, captured


def test_postgres_connection_translates_and_commits(fake_pg):
    raw, captured = fake_pg
    conn = db_layer.connect(PG_URL)
    assert captured["dsn"] == PG_URL
    with conn:
        conn.execute("SELECT * FROM t WHERE a = ?", (1,))
    assert raw.statements[0][0] == "SELECT * FROM t WHERE a = %s"
    assert raw.committed >= 1


def test_database_save_run_uses_returning_on_postgres(fake_pg):
    raw, _ = fake_pg
    database = Database(PG_URL)
    assert database.dialect == "postgres"
    run_id = database.save_run({"skills": "python"}, [], "offline", True)
    assert run_id == 42
    insert_sql = next(s for s, _ in raw.statements if "INSERT INTO recommendation_runs" in s)
    assert "%s" in insert_sql and "RETURNING id" in insert_sql


def test_migrations_run_translated_on_postgres(fake_pg):
    raw, _ = fake_pg
    from career_guidance.migrations import LATEST_VERSION, migrate

    applied = migrate(PG_URL)
    assert applied == list(range(1, LATEST_VERSION + 1))
    sql_text = "\n".join(s for s, _ in raw.statements)
    assert "AUTOINCREMENT" not in sql_text
    assert "GENERATED BY DEFAULT AS IDENTITY" in sql_text
    # Second run is a no-op (versions recorded in the version table).
    assert migrate(PG_URL) == []


